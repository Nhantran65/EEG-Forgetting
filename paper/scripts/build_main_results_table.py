#!/usr/bin/env python3
"""Build Table II and its entry in the shared Markdown from verified cells."""
import hashlib
import json
import re
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PAPER = ROOT / "paper"
SOURCE = ROOT / "results/xai/high_gamma_replacement_ped_v1/summary.json"
DIRECTIONS = (
    ("bciciv2a<-high_gamma", "BCI ← High-Gamma", r"BCI $\leftarrow$ High-Gamma", 3),
    ("bciciv2a<-sleep_edf_sc", "BCI ← Sleep", r"BCI $\leftarrow$ Sleep", 6),
    ("high_gamma<-bciciv2a", "High-Gamma ← BCI", r"High-Gamma $\leftarrow$ BCI", 6),
    ("high_gamma<-sleep_edf_sc", "High-Gamma ← Sleep", r"High-Gamma $\leftarrow$ Sleep", 6),
)
METHODS = ("sequential_finetuning", "ewc", "derpp")


def main():
    digest = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    assert digest == "2005ef2c8b62207fed1215f896ce855a537ede128f39c12c2d1fe00b3027cc43"
    summary = json.loads(SOURCE.read_text())
    tex_rows, md_rows, verified = [], [], []
    for direction, label, tex_label, n in DIRECTIONS:
        formatted = []
        paired_keys = []
        for method in METHODS:
            cells = [c for c in summary["cells"] if c["method"] == method and c["direction"] == direction]
            assert len(cells) == n and all(c["relative_valid"] for c in cells)
            paired_keys.append({(c["order"], c["seed"]) for c in cells})
            assert len(paired_keys[-1]) == n
            for metric, aggregate_name in (("relative_forgetting", "relative_forgetting"),
                                           ("mean_subject_ped", "mean_subject_ped")):
                values = [c[metric] for c in cells]
                mean, sd = statistics.mean(values), statistics.stdev(values)
                saved = summary["aggregates"][method][direction][aggregate_name]
                assert saved["n"] == n
                assert abs(mean-saved["mean"]) < 1e-12 and abs(sd-saved["sample_sd"]) < 1e-12
                decimals = 4 if metric == "mean_subject_ped" and abs(mean) < .001 else 3
                formatted.append(f"{mean:.{decimals}f} ± {sd:.{decimals}f}")
                verified.append(dict(direction=direction, method=method, metric=metric, n=n, mean=mean, sample_sd=sd))
        assert paired_keys[0] == paired_keys[1] == paired_keys[2]
        md_rows.append("| " + " | ".join([label, str(n), *formatted]) + " |")
        tex_rows.append(" & ".join([tex_label, str(n), *[v.replace("±", r"$\pm$") for v in formatted]]) + r" \\")
    tex = r"""% Generated by paper/scripts/build_main_results_table.py; requires booktabs.
\begin{table*}[t]
\centering
\caption{Stage-wise performance forgetting and explanation drift in three-task continual learning.}
\label{tab:continual-results}
\begingroup
\fontsize{8}{9.5}\selectfont
\setlength{\tabcolsep}{3pt}
\renewcommand{\arraystretch}{1.2}
\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lrcccccc@{}}
\toprule
 & & \multicolumn{2}{c}{Sequential FT} & \multicolumn{2}{c}{EWC} & \multicolumn{2}{c}{DER++} \\
\cmidrule(lr){3-4}\cmidrule(lr){5-6}\cmidrule(lr){7-8}
\shortstack[l]{Old task $\leftarrow$\\newly learned task} & $n$ & $F_{rel}$ & PED & $F_{rel}$ & PED & $F_{rel}$ & PED \\
\midrule
""" + "\n".join(tex_rows) + r"""
\bottomrule
\end{tabular*}
\par\vspace{3pt}
\begin{minipage}{\textwidth}
\fontsize{7}{8.3}\selectfont
Every run learns all three tasks and evaluates all seen tasks after each stage.
Each row compares the old task immediately before and after learning the indicated new task,
within that three-task sequence, rather than an isolated two-task run or a first-to-final comparison.
For example, in BCI $\to$ High-Gamma $\to$ Sleep,
BCI $\leftarrow$ Sleep compares BCI at stages 2 and 3, retaining the preceding High-Gamma training history.
Entries are mean $\pm$ sample SD across matched order--seed transition cells;
$n$ is the number of cells per method, not independent subjects.
Performance is mean subject-balanced accuracy on test data;
relative forgetting is the before-minus-after drop divided by before-minus-chance headroom.
Negative values indicate backward transfer.
PED is subject-level, noise-corrected explanation drift on fixed validation splits;
smaller values indicate less attribution change, not necessarily better learning.
Both measures are dimensionless.
Only BCI and High-Gamma are eligible old-task PED targets; Sleep remains a new task.
\end{minipage}
\endgroup
\end{table*}
"""
    (PAPER / "table2_main.tex").write_text(tex)
    wrapper = (PAPER / "tables/table1_reliability_preview.tex").read_text()
    wrapper = wrapper.replace("table1_reliability.tex", "table2_main.tex")
    wrapper = wrapper.replace("3.7in", "7.36in").replace("3.5in", "7.16in")
    wrapper = wrapper.replace(r"\input{table2_main.tex}", r"\setcounter{table}{1}" + "\n" + r"\input{table2_main.tex}")
    (PAPER / "table2_main_preview.tex").write_text(wrapper)
    section = """## Table II — Main Continual-Learning Results

| Old task ← Newly learned task | n | Sequential FT: F_rel | Sequential FT: PED | EWC: F_rel | EWC: PED | DER++: F_rel | DER++: PED |
|---|---:|---:|---:|---:|---:|---:|---:|
""" + "\n".join(md_rows) + """

[LaTeX](table2_main.tex) · [PDF](table2_main_preview.pdf)

Mỗi run học đủ **ba task**, với đánh giá lại tất cả task đã học sau từng stage.

Ví dụ thứ tự **BCI → High-Gamma → Sleep**:

| Thời điểm | Model vừa học xong | Các task được đánh giá |
|---|---|---|
| Stage 1 | BCI | BCI |
| Stage 2 | High-Gamma | BCI, High-Gamma |
| Stage 3 | Sleep | BCI, High-Gamma, Sleep |

Vì vậy, trong thứ tự này:

- **BCI ← High-Gamma:** So kết quả BCI ở stage 1 với stage 2 để đo tác động của việc học High-Gamma.
- **BCI ← Sleep:** So kết quả BCI ở stage 2 với stage 3 để đo tác động tiếp theo của việc học Sleep.
- **High-Gamma ← Sleep:** So kết quả High-Gamma ở stage 2 với stage 3 để đo tác động của việc học Sleep.

**Mỗi hàng đo một bước chuyển trong chuỗi ba task, không phải một run riêng chỉ học A → B.**
Bảng tổng hợp các bước chuyển tương ứng từ cả ba thứ tự học, nên hàng **High-Gamma ← BCI** đến từ những thứ tự mà High-Gamma được học trước BCI.

Các giá trị là **mean ± sample SD** trên `n` cell order–seed ghép cặp, không phải `n` subject độc lập; F_rel âm biểu thị cải thiện hiệu năng trên test, còn PED đo thay đổi attribution trên validation.
"""
    path = PAPER / "figures-and-tables.md"
    current = path.read_text()
    if "## Table II —" in current:
        current = re.sub(r"## Table II —.*?(?=\n## |\Z)", lambda _: section.rstrip()+"\n", current, flags=re.S)
    else:
        current = current.rstrip() + "\n\n" + section
    path.write_text(current)
    (PAPER / "table2_main.sources.json").write_text(json.dumps(
        {"source": str(SOURCE.relative_to(ROOT)), "sha256": digest,
         "aggregation": "mean and sample SD (ddof=1) across matched order-seed cells",
         "verified_statistics": verified}, indent=2) + "\n")
    print(f"Verified {len(verified)} mean/SD pairs and matching cells; wrote Table II.")


if __name__ == "__main__":
    main()
